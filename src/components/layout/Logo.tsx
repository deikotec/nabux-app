/** Ícono de la app: el isotipo en un cuadrado redondeado. `inverted` = cuadrado blanco y ala verde (sobre fondos verdes). */
export function LogoMark({ className, inverted }: { className?: string; inverted?: boolean }) {
  return (
    <svg viewBox={ICON_VIEWBOX} className={cn('size-9 shrink-0', className)} aria-hidden>
      <rect width="1340.91" height="1340.91" rx="143.25" fill={inverted ? '#ffffff' : BRAND.green} />
      <path d={ICON_WING} fill={inverted ? BRAND.green : BRAND.light} />
      <path d={ICON_MOON} fill={BRAND.bright} />
    </svg>
  );
}

/** Isotipo sin fondo. `tone`: color (sobre claro), on-dark (ala clara, sobre oscuro) o white (todo blanco). */
export function Isotipo({ className, tone = 'color' }: { className?: string; tone?: 'color' | 'on-dark' | 'white' }) {
  const wing = tone === 'color' ? BRAND.green : tone === 'on-dark' ? BRAND.light : '#ffffff';
  const moon = tone === 'white' ? '#ffffff' : BRAND.bright;
  return (
    <svg viewBox={ISO_VIEWBOX} className={cn('h-9 w-auto shrink-0', className)} aria-hidden>
      <path d={ISO_WING} fill={wing} />
      <path d={ISO_MOON} fill={moon} />
    </svg>
  );
}

/** Logotipo horizontal (isotipo + "nabux"). `light` = todo en blanco, para fondos verdes u oscuros. */
export function Logo({ className, light }: { className?: string; light?: boolean }) {
  const main = light ? '#ffffff' : BRAND.green;
  return (
    <svg viewBox={LOGO_VIEWBOX} className={cn('h-8 w-auto shrink-0', className)} role="img" aria-label="Nabux">
      <path d={LOGO_WING} fill={main} />
      <path d={LOGO_MOON} fill={light ? '#ffffff' : BRAND.bright} />
      {LOGO_LETTERS.map((d) => (
        <path key={d.slice(0, 16)} d={d} fill={main} />
      ))}
    </svg>
  );
}
